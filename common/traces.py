def round_time(cost_model, k: int, B: int, gamma, prompt_len: int, starts: np.ndarray) -> np.ndarray:
    """Predicted time of rounds that start at `starts` (committed-token index) under the
    synchronous-batch approximation: gamma draft steps + one verify step, all B requests
    in the same state (ASPIRE's homogeneous-batch approximation)."""
    ctx = prompt_len + np.asarray(starts, dtype=np.float64)
    g = np.asarray(gamma, dtype=np.float64)
    return g * cost_model.sync_draft(k, B, ctx) + cost_model.sync_verify(k, g, B, ctx)


def static_score(trace: "Trace", col: int, k: int, gamma: int, cost_model, B: int):
    """(committed tokens, predicted time, accepted per round) for one request, static (k, gamma).
    The final round is truncated by the end of the trace and kept (it is real work)."""
    run = run_lengths(trace.agree[:, col])
    starts, acc, committed = simulate_rounds(run, gamma)
    t = round_time(cost_model, k, B, gamma, trace.prompt_len, starts)
    return float(committed.sum()), float(t.sum()), acc


def load_trace_files(paths, **kw) -> TraceSet:
    """Load several trace files (e.g. one per dataset) into one pooled TraceSet."""
    sets = [load_traces(p, **kw) for p in paths]
    layers = sets[0].exit_layers
    for s in sets[1:]:
        if s.exit_layers != layers or s.n_layers != sets[0].n_layers:
            raise ValueError("trace files were collected with different exit-layer sets / models")
    meta = {**sets[0].meta, "datasets": [s.meta.get("dataset") for s in sets], "files": [str(p) for p in paths]}
    return TraceSet(layers, sets[0].n_layers, [t for s in sets for t in s.traces], meta)


# ----------------------------------------------------------------------------- data quality

def self_repetition(tokens: np.ndarray, n: int = 8) -> float:
    """Share of generated n-grams that already occurred earlier in the *generated* text
    (copying from the prompt does not count).  ~0 for normal text; a base model that loops
    ("The resort is a popular destination ... The resort is a popular destination ...")
    approaches 1.  Degenerate loops are trivially predictable by a shallow exit, so
    requests with a high value are reported and excluded in robustness checks."""
    t = np.asarray(tokens).tolist()
    if len(t) <= n:
        return 0.0
    seen, rep = set(), 0
    for i in range(len(t) - n + 1):
        g = tuple(t[i:i + n])
        rep += g in seen
        seen.add(g)
    return rep / (len(t) - n + 1)
