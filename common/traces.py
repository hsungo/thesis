"""Agreement traces (plan sec.3.1) and the round simulator built on them.

Key property (greedy): a draft token can only be accepted if every earlier draft of
the round was accepted, i.e. the prefix equals the full model's output.  Under that
prefix the exit-layer-k draft equals argmax(LMHead(norm(h_k))) of the *full model's*
AR pass at the same position (shallow layers see the same inputs and the same exact
shallow KV).  So one AR generation that records, at every position, the argmax of
every exit layer gives the exact accepted length of every round for every
(exit layer k, draft length gamma), for any scheduler that only decides *when* to
verify.

Trace layout (one .npz per dataset run)
--------------------------------------
    exit_layers  [n_l]        candidate exit layers k (1-based: "run layers 0..k-1")
    prompt_lens  [R]
    offsets      [R+1]        request r owns rows offsets[r]:offsets[r+1]
    tokens       [S]          token generated by the full model at each position (y_t)
    exit_argmax  [S, n_l]     argmax of exit layer k at the step that produced y_t
    accept_prob  [S, n_l]     (sampling only) sum_x min(p_N(x), p_k(x)) at temperature T
    meta         json string

Row t of a request corresponds to generated token y_t; y_0 comes from the prefill.
Draft j (1-based) of a round that starts with c committed tokens predicts y_{c+j-1}
and is correct iff agree[c+j-1].  A round therefore accepts a = min(run[c], gamma)
drafts and commits a+1 tokens (the bonus token from the verifier).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import numpy as np
import torch


# ----------------------------------------------------------------------------- collection

class ExitProbe:
    """Observer for `ARBatchEngine` that records every exit layer's prediction."""

    def __init__(self, model, exit_layers: list[int], temperature: float = 0.0, chunk_rows: int = 512):
        self.model = model
        self.exit_layers = list(exit_layers)
        self.temperature = temperature
        self.chunk_rows = chunk_rows
        self.buffers: dict[int, dict[str, list]] = {}
        self.finished: list[dict] = []

    @torch.inference_mode()
    def _probe(self, hidden: list[torch.Tensor], full_logits: torch.Tensor):
        """hidden: N tensors [B, dim] (output of every layer); full_logits [B, V].
        Returns argmax [B, n_l] (int32 numpy) and accept prob [B, n_l] or None."""
        H = torch.stack([hidden[k - 1] for k in self.exit_layers], dim=0)          # [n_l, B, dim]
        n_l, B, D = H.shape
        flat = H.reshape(n_l * B, D)
        am = torch.empty(n_l * B, dtype=torch.int32, device=flat.device)
        pr = torch.empty(n_l * B, dtype=torch.float32, device=flat.device) if self.temperature > 0 else None
        if pr is not None:
            p_full = torch.softmax(full_logits.float() / self.temperature, dim=-1)       # [B, V]
        for s in range(0, flat.shape[0], self.chunk_rows):
            logits = self.model.head(flat[s:s + self.chunk_rows])
            am[s:s + self.chunk_rows] = logits.argmax(-1).int()
            if pr is not None:
                rows = torch.arange(s, min(s + self.chunk_rows, flat.shape[0]), device=flat.device)
                pk = torch.softmax(logits.float() / self.temperature, dim=-1)
                pr[s:s + self.chunk_rows] = torch.minimum(pk, p_full[rows % B]).sum(-1)
        am = am.view(n_l, B).T.cpu().numpy()
        pr = pr.view(n_l, B).T.cpu().numpy() if pr is not None else None
        return am, pr

    def on_prefill(self, slot, state, hidden, logits, token) -> None:
        am, pr = self._probe([h.unsqueeze(0) for h in hidden], logits.unsqueeze(0))
        self.buffers[slot] = {"argmax": [am[0]], "prob": [pr[0]] if pr is not None else []}

    def on_step(self, engine, hidden, logits, next_tokens) -> None:
        am, pr = self._probe(hidden, logits)
        for i, s in enumerate(engine.slots):
            if s.idle or s.finish_reason is not None:
                continue
            self.buffers[i]["argmax"].append(am[i])
            if pr is not None:
                self.buffers[i]["prob"].append(pr[i])

    def on_finish(self, slot, state) -> None:
        buf = self.buffers.pop(slot)
        n = len(state.output)
        argmax = np.stack(buf["argmax"][:n]).astype(np.int32)
        rec = {
            "pid": state.pid, "prompt_len": state.prompt_len,
            "tokens": np.asarray(state.output[:n], dtype=np.int32), "exit_argmax": argmax,
            "finish_reason": state.finish_reason,
        }
        if buf["prob"]:
            rec["accept_prob"] = np.stack(buf["prob"][:n]).astype(np.float16)
        self.finished.append(rec)

    def save(self, path: str | Path, meta: dict) -> Path:
        recs = self.finished
        offsets = np.cumsum([0] + [len(r["tokens"]) for r in recs])
        arrays = {
            "exit_layers": np.asarray(self.exit_layers, dtype=np.int32),
            "prompt_lens": np.asarray([r["prompt_len"] for r in recs], dtype=np.int32),
            "offsets": offsets.astype(np.int64),
            "tokens": np.concatenate([r["tokens"] for r in recs]),
            "exit_argmax": np.concatenate([r["exit_argmax"] for r in recs]),
        }
        if recs and "accept_prob" in recs[0]:
            arrays["accept_prob"] = np.concatenate([r["accept_prob"] for r in recs])
        meta = {**meta, "pids": [r["pid"] for r in recs], "finish_reasons": [r["finish_reason"] for r in recs]}
        arrays["meta"] = np.asarray(json.dumps(meta))
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(path, **arrays)
        return path


# ----------------------------------------------------------------------------- loading

@dataclass
class Trace:
    pid: str
    prompt_len: int
    tokens: np.ndarray        # [T]
    agree: np.ndarray         # [T, n_l] bool (greedy) - for sampling: Monte-Carlo draw from accept_prob
    accept_prob: Optional[np.ndarray] = None

    @property
    def length(self) -> int:
        return len(self.tokens)


@dataclass
class TraceSet:
    exit_layers: list[int]
    n_layers: int
    traces: list[Trace]
    meta: dict

    def col(self, k: int) -> int:
        return self.exit_layers.index(k)


def load_traces(path: str | Path, min_len: int = 2, mc_seed: int = 0) -> TraceSet:
    z = np.load(path, allow_pickle=False)
    meta = json.loads(str(z["meta"]))
    layers = z["exit_layers"].tolist()
    off = z["offsets"]
    tokens, am = z["tokens"], z["exit_argmax"]
    prob = z["accept_prob"] if "accept_prob" in z.files else None
    rng = np.random.default_rng(mc_seed)
    out = []
    for r in range(len(off) - 1):
        a, b = off[r], off[r + 1]
        if b - a < min_len:
            continue
        tok = tokens[a:b]
        if prob is None:
            agree = am[a:b] == tok[:, None]
        else:
            p = prob[a:b].astype(np.float32)
            agree = rng.random(p.shape) < p
        out.append(Trace(meta["pids"][r], int(z["prompt_lens"][r]), tok, agree,
                         prob[a:b] if prob is not None else None))
    return TraceSet(layers, int(meta["n_layers"]), out, meta)


# ----------------------------------------------------------------------------- simulation

def run_lengths(agree_col: np.ndarray) -> np.ndarray:
    """run[t] = number of consecutive True values starting at t."""
    T = len(agree_col)
    idx = np.arange(T)
    nxt_false = np.where(~agree_col, idx, T)
    nxt_false = np.minimum.accumulate(nxt_false[::-1])[::-1]
    return nxt_false - idx


def simulate_rounds(run: np.ndarray, gamma: int, start: int = 1):
    """Static draft length.  Returns (round start positions, accepted drafts, committed tokens)."""
    T = len(run)
    r = run.tolist()
    c = start
    starts, acc = [], []
    while c < T:
        a = r[c] if r[c] < gamma else gamma
        starts.append(c)
        acc.append(a)
        c += a + 1
    starts = np.asarray(starts, dtype=np.int64)
    acc = np.asarray(acc, dtype=np.int64)
    committed = np.minimum(acc + 1, T - starts)
    return starts, acc, committed


